//! Export of kernel proofs to Lean 4 (spec.txt §12, phase 8).
//!
//! The kernel has no trusted role here. The export writes the kernel's
//! environment (sorts, symbols, axioms) as Lean `axiom`s and each proof as a
//! Lean `theorem`. Lean then checks every proof term again. A proof accepted by
//! Lean is an independent check of it, relative to the exported axioms.
//!
//! Limitations:
//! - Inductive types are not exported as Lean `inductive` declarations. Their
//!   constructors are uninterpreted symbols and their induction principle is
//!   an exported axiom, so Lean does not check that the sort is free.
//! - Case analysis on an inductive sort (`ProofTerm::Cases`) is rejected with
//!   [`ExportError::UnsupportedRule`], because the sort has no Lean `casesOn`.
//! - Only the lemmas passed to [`export`] are exported. A proof may refer to an
//!   earlier lemma, but not to a kernel theorem whose proof term is not given.

#![forbid(unsafe_code)]

use std::fmt;

use tpt_proof_kernel::terms::{ProofTerm, Prop, Term};
use tpt_proof_kernel::Kernel;

/// A theorem to export, with the proof term that establishes it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Lemma {
    /// The theorem's name. Later lemmas refer to it with `ProofTerm::Const`.
    pub name: String,
    /// The proposition proved.
    pub prop: Prop,
    /// The proof term.
    pub proof: ProofTerm,
}

/// Why a proof could not be exported.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ExportError {
    /// A name contains `»`, which cannot appear in a Lean quoted identifier.
    BadName(String),
    /// A proof refers to a theorem that is not an earlier lemma.
    UnknownTheorem(String),
    /// A proof refers to an axiom the kernel does not declare.
    UnknownAxiom(String),
    /// A proof uses a rule the export does not translate, such as case analysis
    /// on an inductive sort, which Lean sees only as an uninterpreted type.
    UnsupportedRule(String),
}

impl fmt::Display for ExportError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ExportError::BadName(name) => write!(f, "`{name}` cannot be exported to Lean"),
            ExportError::UnknownTheorem(name) => write!(
                f,
                "proof refers to theorem `{name}`, which is not an earlier lemma"
            ),
            ExportError::UnknownAxiom(name) => write!(f, "proof refers to unknown axiom `{name}`"),
            ExportError::UnsupportedRule(rule) => write!(f, "cannot export {rule} to Lean"),
        }
    }
}

impl std::error::Error for ExportError {}

/// Writes a Lean 4 file that declares the kernel's environment, then each lemma
/// in order. Lemmas may refer to earlier lemmas and to the kernel's axioms.
pub fn export(kernel: &Kernel, lemmas: &[Lemma]) -> Result<String, ExportError> {
    let mut out =
        String::from("-- Generated by tpt-proof-export. Lean checks every proof below.\n\n");
    for sort in kernel.sorts() {
        out.push_str(&format!("axiom {} : Type\n", quote("sort", sort)?));
    }
    for (name, args, result) in kernel.functions() {
        let mut ty = String::new();
        for arg in args {
            ty.push_str(&format!("{} → ", quote("sort", &arg.0)?));
        }
        ty.push_str(&quote("sort", &result.0)?);
        out.push_str(&format!("axiom {} : {ty}\n", quote("fun", name)?));
    }
    for (name, args) in kernel.predicates() {
        let mut ty = String::new();
        for arg in args {
            ty.push_str(&format!("{} → ", quote("sort", &arg.0)?));
        }
        ty.push_str("Prop");
        out.push_str(&format!("axiom {} : {ty}\n", quote("pred", name)?));
    }
    for axiom in kernel.axioms() {
        let statement = lean_prop(&axiom.prop)?;
        out.push_str(&format!(
            "-- {}\naxiom {} : {statement}\n",
            axiom.justification.replace('\n', " "),
            quote("ax", &axiom.name)?
        ));
    }

    // Like the kernel, a free propositional atom is a hypothesis, so the Lean
    // statement quantifies over it and the proof abstracts it.
    let mut earlier: Vec<(&str, Vec<String>)> = Vec::new();
    for lemma in lemmas {
        let mut statement = lean_prop(&lemma.prop)?;
        let mut proof = lean_proof(kernel, &earlier, &lemma.proof)?;
        let atoms = free_atoms(&lemma.prop);
        for atom in atoms.iter().rev() {
            statement = format!("(∀ ({} : Prop), {statement})", quote("prop", atom)?);
            proof = format!("(fun ({} : Prop) => {proof})", quote("prop", atom)?);
        }
        out.push_str(&format!(
            "\ntheorem {} : {statement} :=\n  {proof}\n",
            quote("thm", &lemma.name)?
        ));
        earlier.push((&lemma.name, atoms));
    }
    Ok(out)
}

/// A Lean identifier for a kernel name, with a prefix that keeps namespaces apart.
fn quote(prefix: &str, name: &str) -> Result<String, ExportError> {
    if name.contains('»') {
        return Err(ExportError::BadName(name.to_string()));
    }
    Ok(format!("«{prefix}:{name}»"))
}

fn lean_term(term: &Term) -> Result<String, ExportError> {
    Ok(match term {
        Term::Var(name) => quote("var", name)?,
        Term::Fun(symbol, args) if args.is_empty() => quote("fun", symbol)?,
        Term::Fun(symbol, args) => {
            let args = args.iter().map(lean_term).collect::<Result<Vec<_>, _>>()?;
            format!("({} {})", quote("fun", symbol)?, args.join(" "))
        }
    })
}

fn lean_prop(prop: &Prop) -> Result<String, ExportError> {
    Ok(match prop {
        Prop::Atom(name) => quote("prop", name)?,
        Prop::Imp(a, b) => format!("({} → {})", lean_prop(a)?, lean_prop(b)?),
        Prop::Forall(name, body) => {
            format!(
                "(∀ ({} : Prop), {})",
                quote("prop", name)?,
                lean_prop(body)?
            )
        }
        Prop::ForallInd(name, sort, body) => format!(
            "(∀ ({} : {}), {})",
            quote("var", name)?,
            quote("sort", &sort.0)?,
            lean_prop(body)?
        ),
        Prop::Eq(a, b) => format!("({} = {})", lean_term(a)?, lean_term(b)?),
        Prop::Pred(symbol, args) if args.is_empty() => quote("pred", symbol)?,
        Prop::Pred(symbol, args) => {
            let args = args.iter().map(lean_term).collect::<Result<Vec<_>, _>>()?;
            format!("({} {})", quote("pred", symbol)?, args.join(" "))
        }
    })
}

fn lean_proof(
    kernel: &Kernel,
    earlier: &[(&str, Vec<String>)],
    term: &ProofTerm,
) -> Result<String, ExportError> {
    let go = |t: &ProofTerm| lean_proof(kernel, earlier, t);
    Ok(match term {
        ProofTerm::Var(name) => quote("hyp", name)?,
        ProofTerm::Const(name) => {
            let Some((_, atoms)) = earlier
                .iter()
                .find(|(earlier_name, _)| earlier_name == name)
            else {
                return Err(ExportError::UnknownTheorem(name.clone()));
            };
            // The lemma quantifies over its free atoms, so they are passed explicitly.
            let mut out = quote("thm", name)?;
            for atom in atoms {
                out = format!("({out} {})", quote("prop", atom)?);
            }
            out
        }
        ProofTerm::Axiom(name) => {
            if kernel.axiom(name).is_none() {
                return Err(ExportError::UnknownAxiom(name.clone()));
            }
            quote("ax", name)?
        }
        ProofTerm::Lam(name, domain, body) => format!(
            "(fun ({} : {}) => {})",
            quote("hyp", name)?,
            lean_prop(domain)?,
            go(body)?
        ),
        ProofTerm::App(function, argument) => format!("({} {})", go(function)?, go(argument)?),
        ProofTerm::TyLam(name, body) => {
            format!("(fun ({} : Prop) => {})", quote("prop", name)?, go(body)?)
        }
        ProofTerm::TyApp(function, argument) => {
            format!("({} {})", go(function)?, lean_prop(argument)?)
        }
        ProofTerm::IndLam(name, sort, body) => format!(
            "(fun ({} : {}) => {})",
            quote("var", name)?,
            quote("sort", &sort.0)?,
            go(body)?
        ),
        ProofTerm::IndApp(function, argument) => {
            format!("({} {})", go(function)?, lean_term(argument)?)
        }
        ProofTerm::Refl(t) => format!("(Eq.refl {})", lean_term(t)?),
        ProofTerm::Sym(p) => format!("(Eq.symm {})", go(p)?),
        ProofTerm::Trans(p, q) => format!("(Eq.trans {} {})", go(p)?, go(q)?),
        ProofTerm::Cong(symbol, args) => {
            // `congr` takes one argument equality at a time, so start from reflexivity on the symbol.
            let mut out = format!("(Eq.refl {})", quote("fun", symbol)?);
            for arg in args {
                out = format!("(congr {out} {})", go(arg)?);
            }
            out
        }
        // The sort of the variable is left to Lean, which takes it from the equation.
        ProofTerm::Cases(..) => {
            return Err(ExportError::UnsupportedRule(
                "case analysis on an inductive sort".to_string(),
            ))
        }
        ProofTerm::Leibniz(variable, motive, equation, proof) => format!(
            "(Eq.subst (motive := fun ({} : _) => {}) {} {})",
            quote("var", variable)?,
            lean_prop(motive)?,
            go(equation)?,
            go(proof)?
        ),
    })
}

/// The free propositional atoms of `prop`, in order of first occurrence.
fn free_atoms(prop: &Prop) -> Vec<String> {
    fn walk(prop: &Prop, bound: &mut Vec<String>, out: &mut Vec<String>) {
        match prop {
            Prop::Atom(name) => {
                if !bound.contains(name) && !out.contains(name) {
                    out.push(name.clone());
                }
            }
            Prop::Imp(a, b) => {
                walk(a, bound, out);
                walk(b, bound, out);
            }
            Prop::Forall(name, body) => {
                bound.push(name.clone());
                walk(body, bound, out);
                bound.pop();
            }
            Prop::ForallInd(_, _, body) => walk(body, bound, out),
            Prop::Eq(_, _) | Prop::Pred(_, _) => {}
        }
    }
    let mut out = Vec::new();
    walk(prop, &mut Vec::new(), &mut out);
    out
}
